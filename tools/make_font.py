#!/usr/bin/env python3
"""Build TFT_eSPI smooth fonts (.vlw format) as C arrays.

Example:
  python3 tools/make_font.py --font Loma.otf --size 18 --boost 1.7 \
      --chars thai --name fontThai --out src/font_thai.h

--chars: thai   = ASCII + degree sign + Thai + private-use Thai mark variants
         ascii  = printable ASCII + degree sign
         digits = 0-9 . - : / % space
--boost: >1 thickens thin anti-aliased strokes on small TFT panels.
--weight: weight axis value for variable fonts (e.g. 800).
Thai marks keep zero advance and a negative left offset so they sit on the
previous consonant; src/thai_shape.cpp picks the private-use variants.
"""
import argparse
import struct
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("--font", required=True)
ap.add_argument("--size", type=int, required=True)
ap.add_argument("--boost", type=float, default=1.0)
ap.add_argument("--chars", default="thai")
ap.add_argument("--weight", type=float)
ap.add_argument("--name", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()

font = ImageFont.truetype(a.font, a.size, layout_engine=ImageFont.Layout.BASIC)
if a.weight:
    font.set_variation_by_axes([a.weight])

if a.chars == "digits":
    codes = sorted(set(ord(c) for c in "0123456789.-:/% "))
else:
    codes = list(range(0x20, 0x7F)) + [0xB0]
    if a.chars == "thai":
        codes += [c for c in range(0x0E01, 0x0E5C) if c not in range(0x0E3B, 0x0E3F)]
        codes += list(range(0xF700, 0xF71B))

glyphs = []
for cp in codes:
    ch = chr(cp)
    adv = int(round(font.getlength(ch)))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if cp == 0x20 or w <= 0 or h <= 0:
        glyphs.append((cp, 0, 0, adv, 0, 0, b""))
        continue
    pad = a.size
    img = Image.new("L", (w + 3 * pad, h + 3 * pad), 0)
    ox, oy = pad - x0 + pad // 2, pad - y0 + pad // 2
    ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    crop = img.crop((ox + x0, oy + y0, ox + x1, oy + y1))
    bmp = bytes(min(255, int(v * a.boost)) for v in crop.tobytes())
    glyphs.append((cp, h, w, adv, -y0, x0, bmp))

# TFT_eSPI takes maxAscent straight from this header (it does not scan the glyphs),
# so store the real top of the Latin/digit glyphs, not the font's design ascent.
# Thai marks above that line still draw correctly; they just sit a little higher.
latin = [g for g in glyphs if 0x21 <= g[0] <= 0x7E and g[1] > 0]
ascent = max(g[4] for g in latin)
descent = max(max(g[1] - g[4] for g in latin), 0)
out = bytearray()
out += struct.pack(">iiiiii", len(glyphs), 11, a.size, 0, ascent, descent)
for cp, h, w, adv, dy, dx, _ in glyphs:
    out += struct.pack(">iiiiiii", cp, h, w, adv, dy, dx, 0)
for g in glyphs:
    out += g[6]

lines = ["  " + ",".join(f"0x{b:02X}" for b in out[i:i + 20]) + "," for i in range(0, len(out), 20)]
with open(a.out, "w") as f:
    f.write(f"// Generated by tools/make_font.py from {a.font.split('/')[-1]} at {a.size}px\n")
    f.write("#pragma once\n#include <pgmspace.h>\n\n")
    f.write(f"const uint8_t {a.name}[{len(out)}] PROGMEM = {{\n")
    f.write("\n".join(lines))
    f.write("\n};\n")
print(f"{a.name}: {len(glyphs)} glyphs, {len(out)} bytes")
